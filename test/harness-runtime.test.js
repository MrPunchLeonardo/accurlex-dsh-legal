import assert from 'node:assert/strict';
import { test } from 'node:test';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { Context } from '@deepseek-ai/cordis';
import SystemPrompt from '@deepseek-ai/dsh-system-prompt';
import ToolRuntime, { renderToolsSdk, renderToolsSdkPy } from '@deepseek-ai/dsh-tools';
import { createToolDefinitions } from '../src/index.js';

test('current official Harness runtime accepts, renders and executes native connection and business tools', async t => {
  const home = fs.mkdtempSync(path.join(os.tmpdir(), 'accurlex-dsh-sdk-'));
  t.after(() => fs.rmSync(home, { recursive: true, force: true }));
  const ctx = new Context();
  const promptPlugin = ctx.plugin(SystemPrompt, {});
  await promptPlugin.await();
  const runtimePlugin = ctx.plugin(ToolRuntime, {});
  await runtimePlugin.await();
  const calls = [];
  const definitions = createToolDefinitions({}, { home, environment: {}, fetchImpl: async (url, init) => {
    calls.push({ url: String(url), init });
    if (String(url).endsWith('/start')) return Response.json({ status: 'sms_sent', scope: 'contract_review', challenge_id: 'c'.repeat(32) });
    if (String(url).endsWith('/complete')) return Response.json({ status: 'ready', scope: 'contract_review', api_key: 'ak_live_' + 'runtime_test_'.repeat(4) });
    assert.equal(init.headers.Authorization, 'Bearer ak_live_' + 'runtime_test_'.repeat(4));
    return Response.json({ data: '完整合同审查意见', original_content: '合成法条依据' });
  } });
  const plugin = ctx.plugin({ inject: ['tools'], apply(scope) { for (const tool of definitions) scope.tools.register(tool); } });
  t.after(async () => { await plugin.dispose(); await runtimePlugin.dispose(); await promptPlugin.dispose(); });
  await plugin.await();
  assert.equal(ctx.tools.schemas().length, 6);
  const invoke = (name, args) => ctx.tools.execute({ name, arguments: args, callId: 'synthetic-call', signal: new AbortController().signal });
  const status = await invoke('accurlex_connect', { action: 'status', capability: 'contract_review' });
  assert.equal(status.isError, false, JSON.stringify(status));
  assert.equal(status.value.status, 'needs_onboarding');
  assert.match(status.content[0].text, /手机号/);
  const missing = await invoke('accurlex_contract_review', { contract_text: '完整材料', standpoint: '乙方' });
  assert.equal(missing.isError, false, JSON.stringify(missing));
  assert.equal(missing.value.error.code, 'api_key_required');
  assert.match(missing.content[0].text, /accurlex_connect/);
  const invalid = await invoke('accurlex_connect', { action: 'start', capability: 'admin', phone: '18000000000', consent: true });
  assert.equal(invalid.value.error.code, 'invalid_arguments');
  assert.equal(calls.length, 0);
  const sent = await invoke('accurlex_connect', { action: 'start', capability: 'contract_review', phone: '18000000000', consent: true });
  assert.equal(sent.isError, false, JSON.stringify(sent));
  assert.equal(sent.value.status, 'sms_sent');
  assert.match(sent.content[0].text, /connection_id=/);
  const ready = await invoke('accurlex_connect', { action: 'complete', capability: 'contract_review', connection_id: sent.value.connection_id, code: '1234' });
  assert.equal(ready.isError, false, JSON.stringify(ready));
  assert.equal(ready.value.status, 'ready');
  assert.doesNotMatch(JSON.stringify(ready), /ak_live_/);
  const review = await invoke('accurlex_contract_review', { contract_text: '完整合同材料', standpoint: '乙方' });
  assert.equal(review.isError, false, JSON.stringify(review));
  assert.equal(review.content[0].text, '完整合同审查意见');
  assert.equal(calls.length, 3);
  const sdkSchemas = definitions.map(tool => ({ name: tool.name, description: tool.description, parameters: tool.parameters, output: tool.output.schema }));
  assert.match(renderToolsSdk(sdkSchemas), /accurlex_connect/);
  assert.match(renderToolsSdkPy(sdkSchemas), /accurlex_connect/);
  const card = definitions.find(tool => tool.name === 'accurlex_connect').presentCall({ action: 'complete', capability: 'qa_deep', phone: '18000000000', code: '1234' });
  assert.doesNotMatch(JSON.stringify(card), /18000000000|1234/);
});
